#!/usr/bin/env python3
"""Regenerate crates/guff-govet/src/stdlib_manifest.txt from x/tools'
checked-in internal/stdlib/manifest.go.

    python3 scripts/gen-stdlib-manifest.py \
        "$(go env GOMODCACHE)/golang.org/x/tools@v0.50.0" \
        crates/guff-govet/src/stdlib_manifest.txt

manifest.go is generated by x/tools' generate.go from the api/go1.*.txt files
of one specific Go release and then *checked into the repository*: v0.50.0
(golangci-lint 2.14.0's pin) already lists go1.27 symbols. Regenerating it from
a local toolchain would drop or add symbols — and therefore stdversion
findings. This script only transcribes; it never re-derives.

Output: one symbol per line, `pkg<TAB>name<TAB>kind<TAB>minor`, where `minor`
is N of go1.N. The Signature column is not carried; nothing in guff reads it.
"""
import os, re, sys

KINDS = {"Type", "Func", "Var", "Const", "Field", "Method"}
PKG = re.compile(r'^\t"([^"]+)": \{$')
SYM = re.compile(r'^\t\t\{"([^"]+)", (\w+), (\d+), ".*"\},$')


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    src = os.path.join(sys.argv[1], "internal", "stdlib", "manifest.go")
    out = []
    pkg = None
    in_map = False
    for line in open(src, encoding="utf-8"):
        line = line.rstrip("\n")
        if line.startswith("var PackageSymbols = map[string][]Symbol{"):
            in_map = True
            continue
        if not in_map:
            continue
        if line == "}":
            break
        if m := PKG.match(line):
            pkg = m.group(1)
            continue
        if line == "\t},":
            pkg = None
            continue
        m = SYM.match(line)
        if not m or pkg is None:
            # A shape this transcriber does not know: fail rather than drop a
            # symbol silently.
            raise SystemExit(f"unrecognised manifest line: {line!r}")
        name, kind, minor = m.groups()
        if kind not in KINDS:
            raise SystemExit(f"unknown kind {kind!r} in: {line!r}")
        out.append(f"{pkg}\t{name}\t{kind}\t{minor}")
    with open(sys.argv[2], "w", encoding="utf-8") as f:
        f.write("# Transcribed from golang.org/x/tools@v0.50.0 internal/stdlib/manifest.go\n")
        f.write("# by scripts/gen-stdlib-manifest.py. Do not edit. BSD-3-Clause, see\n")
        f.write("# crates/guff-govet/tests/testdata/upstream-x-tools-v0.50/LICENSE.\n")
        for row in out:
            f.write(row + "\n")
    print(f"{len(out)} symbols, {len({r.split(chr(9))[0] for r in out})} packages", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
